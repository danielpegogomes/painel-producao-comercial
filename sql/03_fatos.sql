-- DW: fatos. Produção no grão do contrato; metas no grão mês × agência × produto.

CREATE OR REPLACE TABLE DW.FATO_PRODUCAO AS
SELECT
  C.CONTRATO_ID,
  C.DATA_CONTRATACAO,
  DATE_TRUNC('MONTH', C.DATA_CONTRATACAO) AS MES,
  C.AGENCIA_ID,
  COALESCE(C.GERENTE_ID, -1)              AS GERENTE_ID,
  C.PRODUTO_ID,
  C.CANAL,
  C.FAIXA_ETARIA,
  C.VALOR,
  C.TAXA_AM,
  C.PRAZO_MESES
FROM STAGING.CONTRATOS C
WHERE C.STATUS = 'APROVADO'
  AND C.VALOR > 0;

CREATE OR REPLACE TABLE DW.FATO_META AS
SELECT MES, AGENCIA_ID, PRODUTO_ID, SUM(META) AS META
FROM STAGING.METAS
GROUP BY MES, AGENCIA_ID, PRODUTO_ID;
