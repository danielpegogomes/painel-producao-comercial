-- DW: dimensões do modelo estrela.

CREATE OR REPLACE TABLE DW.DIM_AGENCIA AS
SELECT TRY_TO_NUMBER(AGENCIA_ID) AS AGENCIA_ID, AGENCIA, CIDADE, REGIONAL, TRY_TO_NUMBER(REGIONAL_ID) AS REGIONAL_ID
FROM RAW.AGENCIAS;

CREATE OR REPLACE TABLE DW.DIM_GERENTE AS
SELECT TRY_TO_NUMBER(GERENTE_ID) AS GERENTE_ID, GERENTE, TRY_TO_NUMBER(AGENCIA_ID) AS AGENCIA_ID, CARTEIRA
FROM RAW.GERENTES
UNION ALL
-- membro "desconhecido": contratos sem gerente continuam no painel em vez de sumirem no JOIN
SELECT -1, 'Sem gerente atribuído', NULL, NULL;

CREATE OR REPLACE TABLE DW.DIM_PRODUTO AS
SELECT TRY_TO_NUMBER(PRODUTO_ID) AS PRODUTO_ID, PRODUTO, SEGMENTO,
       CASE WHEN PRODUTO IN ('Consignado INSS', 'Consignado Público', 'Cartão Consignado') THEN 'Consignado'
            WHEN SEGMENTO = 'PJ' THEN 'Crédito PJ'
            WHEN PRODUTO = 'Crédito Pessoal' THEN 'Crédito PF'
            ELSE 'Investimentos e Seguros' END AS FAMILIA
FROM RAW.PRODUTOS;

CREATE OR REPLACE TABLE DW.DIM_CANAL AS
SELECT CANAL, IFF(CANAL IN ('App', 'Internet Banking'), 'Digital', 'Físico') AS TIPO_CANAL
FROM (SELECT DISTINCT CANAL FROM STAGING.CONTRATOS);

CREATE OR REPLACE TABLE DW.DIM_TEMPO AS
WITH LIMITES AS (
  SELECT MIN(DATA_CONTRATACAO) AS INICIO, DATEDIFF(DAY, MIN(DATA_CONTRATACAO), MAX(DATA_CONTRATACAO)) AS N
  FROM STAGING.CONTRATOS
),
SEQUENCIA AS (
  SELECT ROW_NUMBER() OVER (ORDER BY CONTRATO_ID) - 1 AS SEQ FROM STAGING.CONTRATOS LIMIT 3000
),
DIAS AS (
  SELECT DATEADD(DAY, S.SEQ, L.INICIO) AS DATA
  FROM LIMITES L JOIN SEQUENCIA S ON S.SEQ <= L.N
)
SELECT DATA,
       DATE_TRUNC('MONTH', DATA) AS MES,
       YEAR(DATA)                AS ANO,
       MONTH(DATA)               AS MES_NUM,
       QUARTER(DATA)             AS TRIMESTRE,
       DAYOFWEEKISO(DATA) >= 6   AS FIM_DE_SEMANA
FROM DIAS;
