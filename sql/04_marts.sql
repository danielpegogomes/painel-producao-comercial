-- MARTS: tabelas prontas para o Power BI e para o relatório automático.

-- Produção × meta por mês, agência e produto (base do painel)
CREATE OR REPLACE TABLE MARTS.PRODUCAO_X_META AS
WITH REALIZADO AS (
  SELECT F.MES, F.AGENCIA_ID, F.PRODUTO_ID,
         SUM(F.VALOR)                                   AS PRODUCAO,
         COUNT(*)                                       AS CONTRATOS,
         SUM(IFF(K.TIPO_CANAL = 'Digital', F.VALOR, 0)) AS PRODUCAO_DIGITAL,
         SUM(F.VALOR * F.TAXA_AM) / NULLIF(SUM(IFF(F.TAXA_AM IS NULL, 0, F.VALOR)), 0) AS TAXA_MEDIA_PONDERADA
  FROM DW.FATO_PRODUCAO F
  JOIN DW.DIM_CANAL K ON K.CANAL = F.CANAL
  GROUP BY F.MES, F.AGENCIA_ID, F.PRODUTO_ID
)
SELECT COALESCE(R.MES, M.MES)               AS MES,
       COALESCE(R.AGENCIA_ID, M.AGENCIA_ID) AS AGENCIA_ID,
       COALESCE(R.PRODUTO_ID, M.PRODUTO_ID) AS PRODUTO_ID,
       A.AGENCIA, A.REGIONAL, P.PRODUTO, P.SEGMENTO, P.FAMILIA,
       COALESCE(R.PRODUCAO, 0)         AS PRODUCAO,
       COALESCE(R.CONTRATOS, 0)        AS CONTRATOS,
       COALESCE(R.PRODUCAO_DIGITAL, 0) AS PRODUCAO_DIGITAL,
       R.TAXA_MEDIA_PONDERADA,
       COALESCE(M.META, 0)             AS META
FROM REALIZADO R
FULL OUTER JOIN DW.FATO_META M
  ON M.MES = R.MES AND M.AGENCIA_ID = R.AGENCIA_ID AND M.PRODUTO_ID = R.PRODUTO_ID
JOIN DW.DIM_AGENCIA A ON A.AGENCIA_ID = COALESCE(R.AGENCIA_ID, M.AGENCIA_ID)
JOIN DW.DIM_PRODUTO P ON P.PRODUTO_ID = COALESCE(R.PRODUTO_ID, M.PRODUTO_ID);

-- Mix de canais por mês, regional e produto
CREATE OR REPLACE TABLE MARTS.MIX_CANAIS AS
SELECT F.MES, A.REGIONAL, P.PRODUTO, P.SEGMENTO, F.CANAL, K.TIPO_CANAL,
       SUM(F.VALOR) AS PRODUCAO, COUNT(*) AS CONTRATOS
FROM DW.FATO_PRODUCAO F
JOIN DW.DIM_AGENCIA A ON A.AGENCIA_ID = F.AGENCIA_ID
JOIN DW.DIM_PRODUTO P ON P.PRODUTO_ID = F.PRODUTO_ID
JOIN DW.DIM_CANAL K   ON K.CANAL = F.CANAL
GROUP BY F.MES, A.REGIONAL, P.PRODUTO, P.SEGMENTO, F.CANAL, K.TIPO_CANAL;

-- Ranking das regionais no acumulado do ano, com variação contra o mesmo período do ano anterior
CREATE OR REPLACE TABLE MARTS.RANKING_REGIONAL_YTD AS
WITH ULTIMO AS (
  SELECT MAX(MES) AS MES_REF FROM MARTS.PRODUCAO_X_META WHERE PRODUCAO > 0
),
BASE AS (
  SELECT X.REGIONAL,
         SUM(IFF(YEAR(X.MES) = YEAR(U.MES_REF) AND X.MES <= U.MES_REF, X.PRODUCAO, 0)) AS PRODUCAO_YTD,
         SUM(IFF(YEAR(X.MES) = YEAR(U.MES_REF) AND X.MES <= U.MES_REF, X.META, 0))     AS META_YTD,
         SUM(IFF(YEAR(X.MES) = YEAR(U.MES_REF) - 1 AND X.MES <= DATEADD(YEAR, -1, U.MES_REF), X.PRODUCAO, 0)) AS PRODUCAO_YTD_ANO_ANTERIOR
  FROM MARTS.PRODUCAO_X_META X
  CROSS JOIN ULTIMO U
  GROUP BY X.REGIONAL
)
SELECT REGIONAL, PRODUCAO_YTD, META_YTD,
       DIV0(PRODUCAO_YTD, META_YTD)                             AS ATINGIMENTO,
       DIV0(PRODUCAO_YTD, PRODUCAO_YTD_ANO_ANTERIOR) - 1        AS VARIACAO_AA,
       RANK() OVER (ORDER BY DIV0(PRODUCAO_YTD, META_YTD) DESC) AS POSICAO
FROM BASE;

-- Gerentes por mês: produção, contratos e participação na produção da agência
CREATE OR REPLACE TABLE MARTS.GERENTES_MENSAL AS
SELECT F.MES, G.GERENTE_ID, G.GERENTE, A.AGENCIA, A.REGIONAL,
       SUM(F.VALOR) AS PRODUCAO,
       COUNT(*)     AS CONTRATOS,
       DIV0(SUM(F.VALOR), SUM(SUM(F.VALOR)) OVER (PARTITION BY F.MES, F.AGENCIA_ID)) AS PARTICIPACAO_AGENCIA
FROM DW.FATO_PRODUCAO F
JOIN DW.DIM_GERENTE G ON G.GERENTE_ID = F.GERENTE_ID
JOIN DW.DIM_AGENCIA A ON A.AGENCIA_ID = F.AGENCIA_ID
GROUP BY F.MES, G.GERENTE_ID, G.GERENTE, A.AGENCIA, A.REGIONAL, F.AGENCIA_ID;
